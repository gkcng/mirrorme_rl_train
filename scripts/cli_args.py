"""Small subset of the official Isaac Lab RSL-RL CLI helper."""

from __future__ import annotations

import argparse
import os
import random


def add_rsl_rl_args(parser: argparse.ArgumentParser) -> None:
    group = parser.add_argument_group("rsl_rl", description="RSL-RL options")
    group.add_argument("--experiment_name", type=str, default=None)
    group.add_argument("--run_name", type=str, default=None)
    group.add_argument("--resume", action="store_true", default=False)
    group.add_argument("--load_run", type=str, default=None)
    group.add_argument("--checkpoint", type=str, default=None)
    group.add_argument("--logger", type=str, default=None, choices={"wandb", "tensorboard", "neptune"})
    group.add_argument("--log_project_name", type=str, default=None)


def update_rsl_rl_cfg(agent_cfg, args_cli):
    if hasattr(args_cli, "seed") and args_cli.seed is not None:
        if args_cli.seed == -1:
            args_cli.seed = random.randint(0, 10000)
        agent_cfg.seed = args_cli.seed
    if args_cli.resume is not None:
        agent_cfg.resume = args_cli.resume
    if args_cli.load_run is not None:
        agent_cfg.load_run = args_cli.load_run
    if args_cli.checkpoint is not None:
        agent_cfg.load_checkpoint = args_cli.checkpoint
    if args_cli.run_name is not None:
        agent_cfg.run_name = args_cli.run_name
    if args_cli.experiment_name is not None:
        agent_cfg.experiment_name = args_cli.experiment_name
    if args_cli.logger is not None:
        agent_cfg.logger = args_cli.logger
    if agent_cfg.logger in {"wandb", "neptune"} and args_cli.log_project_name:
        agent_cfg.wandb_project = args_cli.log_project_name
        agent_cfg.neptune_project = args_cli.log_project_name
    return agent_cfg


def resolve_task_from_registry(requested_task: str | None = None, checkpoint: str | None = None) -> str:
    """Dynamically discover task name from checkpoint params, directory path, or Gym registry."""
    # 1. Explicit CLI argument takes highest priority
    if requested_task:
        return requested_task

    if checkpoint:
        ckpt_path = os.path.abspath(checkpoint)
        run_dir = os.path.dirname(ckpt_path) if os.path.isfile(ckpt_path) else ckpt_path

        # 2. Inspect params/agent.yaml generated by train.py
        agent_yaml = os.path.join(run_dir, "params", "agent.yaml")
        if os.path.isfile(agent_yaml):
            try:
                import yaml

                with open(agent_yaml, "r") as f:
                    cfg_data = yaml.safe_load(f)
                    if isinstance(cfg_data, dict) and "experiment_name" in cfg_data:
                        exp_name = cfg_data["experiment_name"]
                        if exp_name and isinstance(exp_name, str):
                            return exp_name
            except Exception:
                pass

        # 3. Inspect directory hierarchy (e.g. logs/bpx_backflip/YYYY-MM-DD_.../model.pt)
        parent_dir = os.path.basename(os.path.dirname(run_dir))
        if parent_dir.startswith("bpx_"):
            return parent_dir

        current_dir = os.path.basename(run_dir)
        if current_dir.startswith("bpx_"):
            return current_dir

        # Check full path string for any bpx_ directory segment
        for segment in ckpt_path.split(os.sep):
            if segment.startswith("bpx_"):
                return segment

    # 4. Fallback: discover via Gymnasium registry (handling both keys and EnvSpec values)
    try:
        import gymnasium as gym
        import mirrorme_rl_train.tasks  # noqa: F401

        registered_tasks = []
        for key, spec in gym.registry.items():
            task_id = getattr(spec, "id", str(key))
            if task_id.startswith("bpx_"):
                registered_tasks.append(task_id)

        registered_tasks = sorted(set(registered_tasks), key=len, reverse=True)
        if checkpoint and registered_tasks:
            norm_ckpt = os.path.abspath(checkpoint)
            for task in registered_tasks:
                if task in norm_ckpt:
                    return task
        if registered_tasks:
            return registered_tasks[0]
    except Exception:
        pass

    return "bpx_flat"
